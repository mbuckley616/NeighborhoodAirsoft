import { boot } from './lib/game.mjs';
import fs from 'fs';
const g = await boot(); const { page } = g;
await g.bedroom();
const type = process.env.GUN;
const r = await page.evaluate((type) => {
  const m = buildBareGunMesh(type);
  if (m.parent) m.parent.remove(m);
  m.position.set(0, 0, 0); m.rotation.set(0, 0, 0); m.updateWorldMatrix(true, true);
  const all = new THREE.Box3();
  m.traverse(o => { if (!o.isMesh) return; o.geometry.computeBoundingBox(); all.union(o.geometry.boundingBox.clone().applyMatrix4(o.matrixWorld)); });
  const out = {};
  const Wd = 900, H = 450;
  const rd = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
  rd.setSize(Wd, H); rd.setClearColor(0xe8e4da, 1);
  const sc = new THREE.Scene(); sc.add(new THREE.AmbientLight(0xffffff, 0.75));
  const dl = new THREE.DirectionalLight(0xffffff, 0.9); dl.position.set(1, 2, 1); sc.add(dl); sc.add(m);
  const c = new THREE.Vector3(); all.getCenter(c); const half = 0.16;
  const cam = new THREE.OrthographicCamera(-half * Wd / H, half * Wd / H, half, -half, 0.01, 5);
  cam.position.set(c.x + 1, c.y, c.z); cam.lookAt(c);
  rd.render(sc, cam); out.side = rd.domElement.toDataURL('image/png'); rd.dispose();
  return out;
}, type);
fs.writeFileSync(`${process.env.OUT}/${type}-side.png`, Buffer.from(r.side.split(',')[1], 'base64'));
await g.close();
